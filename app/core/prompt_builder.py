# Построитель промптов для AI
# Этот файл отвечает за:
# - формирование ЧЁТКОЙ инструкции для модели
# - гарантию стабильного формата ответа (чтобы не ломался парсер)
# - описание целей, аудитории и тональности


class PromptBuilder:
    """
    Собирает промпты для:
    1. анализа текста
    2. трансформации текста
    """

    # -------------------------------------------------
    # 🔹 АНАЛИЗ ТЕКСТА
    # -------------------------------------------------
    def build_analyze_prompt(self, text: str) -> str:
        return f"""
Ты — эксперт по анализу текста.

Проанализируй текст и кратко опиши:
1. Основной смысл
2. Стиль
3. Сложность
4. Для какой аудитории он подходит

Текст:
{text}
""".strip()

    # -------------------------------------------------
    # 🔹 ТРАНСФОРМАЦИЯ ТЕКСТА (САМОЕ ВАЖНОЕ)
    # -------------------------------------------------
    def build_transform_prompt(self, request) -> str:
        return f"""
Ты — профессиональный редактор текста.

Твоя задача:
переписать текст под заданные параметры,
СОХРАНЯЯ исходный смысл.

----------------------
🔹 ПАРАМЕТРЫ:
----------------------
Цель: {request.goal}
Аудитория: {request.audience}
Тон: {request.tone}
Формальность: {request.formality or "не задано"}
Длина: {request.length or "не задано"}
Упрощение терминов: {request.simplify or "не задано"}

----------------------
🔹 ПРАВИЛА:
----------------------
- НЕ искажай смысл текста
- Меняй структуру, стиль и подачу
- Учитывай аудиторию
- Делай текст читаемым
- Если аудитория "дети" — упрощай язык
- Если указано simplify — упрощай термины

----------------------
🔹 ФОРМАТ ОТВЕТА (СТРОГО):
----------------------

1. Адаптированный текст:
<тут готовый результат>

2. Нейтральная версия:
<переписанный текст без сильной стилизации>

3. Объяснение:
<что изменено и почему>

----------------------
🔹 ВАЖНО:
----------------------
- НЕ добавляй лишний текст
- НЕ меняй структуру ответа
- ВСЕГДА соблюдай формат

----------------------
🔹 ИСХОДНЫЙ ТЕКСТ:
----------------------
{request.text}
""".strip()
