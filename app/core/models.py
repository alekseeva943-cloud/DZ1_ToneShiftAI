# -------------------------------------------------
# 📦 МОДЕЛИ ДАННЫХ ПРОЕКТА
# -------------------------------------------------
# Этот файл отвечает за:
# - структуру входных данных (что приходит в AI)
# - структуру выходных данных (что AI возвращает)
# - единый контракт между слоями:
#   handlers → core → AI → handlers
# -------------------------------------------------

from dataclasses import dataclass
from typing import Optional


# -------------------------------------------------
# 🔹 ВХОД В AI (запрос пользователя)
# -------------------------------------------------
@dataclass
class TransformRequest:
    """
    📥 Модель запроса на трансформацию текста.

    Используется:
    - в handlers (собираем данные от пользователя)
    - в AIEngine (передаем в LLM)

    ⚠️ Важно:
    Все поля должны совпадать с тем, что ты кладешь в context.user_data

    Поля:
    """

    # -----------------------------
    # ОБЯЗАТЕЛЬНЫЕ ПОЛЯ
    # -----------------------------
    text: str                 # исходный текст
    goal: str                 # цель (продать, объяснить и т.д.)
    audience: str             # аудитория
    tone: str                 # тон

    # -----------------------------
    # ОПЦИОНАЛЬНЫЕ ПОЛЯ
    # (могут быть None)
    # -----------------------------
    formality: Optional[str] = None   # уровень формальности
    length: Optional[str] = None      # длина текста
    simplify: Optional[str] = None    # упрощать термины (да/нет)

    # -----------------------------
    # 🔥 ЗАЩИТА ОТ ПУСТЫХ ДАННЫХ
    # -----------------------------
    def __post_init__(self):
        """
        Автоматически вызывается после создания объекта.

        Нормализуем None → "" чтобы LLM не ломался
        """

        self.formality = self.formality or ""
        self.length = self.length or ""
        self.simplify = self.simplify or ""


# -------------------------------------------------
# 🔹 ВЫХОД ИЗ AI (ответ пользователю)
# -------------------------------------------------
@dataclass
class TransformResponse:
    """
    📤 Модель ответа AI.

    Используется:
    - в AIEngine (формируем результат)
    - в handlers (отправляем пользователю)

    Поля:
    """

    adapted_text: str     # главный результат
    neutral_text: str     # нейтральная версия
    explanation: str      # объяснение + анализ

    # -----------------------------
    # 🔥 ФОЛБЭК НА СЛУЧАЙ КРИВЫХ ДАННЫХ
    # -----------------------------
    def __post_init__(self):
        """
        Если модель вернула None — не падаем
        """

        self.adapted_text = self.adapted_text or "Ошибка генерации текста"
        self.neutral_text = self.neutral_text or "Ошибка генерации"
        self.explanation = self.explanation or "Модель не дала объяснение"
